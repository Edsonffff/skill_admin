create or replace function public.record_license_usage(
  p_license_id bigint,
  p_result text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  license_row public.licenses;
begin
  if p_result not in ('success', 'failure') then
    raise exception 'INVALID_RESULT';
  end if;
  select * into license_row from public.licenses where id = p_license_id for update;
  if license_row.id is null then
    raise exception 'LICENSE_NOT_FOUND';
  end if;
  if license_row.status <> 'active' or license_row.expires_at <= now() then
    raise exception 'LICENSE_NOT_ACTIVE';
  end if;

  update public.licenses
  set total_runs = total_runs + 1,
      successful_runs = successful_runs + case when p_result = 'success' then 1 else 0 end,
      last_activity_at = clock_timestamp(),
      last_used_at = clock_timestamp()
  where id = p_license_id;

  select * into license_row from public.licenses where id = p_license_id;
  return jsonb_build_object(
    'totalRuns', license_row.total_runs,
    'successfulRuns', license_row.successful_runs,
    'lastActivityAt', license_row.last_activity_at
  );
end;
$$;

-- Compatibility overload for older clients. It ignores run_id/language and never
-- inserts a history row; each accepted run report counts once per call.
create or replace function public.record_license_usage(
  p_license_id bigint,
  p_run_id text,
  p_event text,
  p_result text,
  p_language text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_event <> 'run' then raise exception 'INVALID_EVENT'; end if;
  return public.record_license_usage(p_license_id, p_result);
end;
$$;

